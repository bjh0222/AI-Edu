import pw, { CHROME } from "./pw.mjs";
const b = await pw.chromium.launch(CHROME);
const page = await b.newPage();
const errs = [], resp = [];
page.on("console", m => { if (m.type()==="error") errs.push("CONSOLE: "+m.text().slice(0,300)); });
page.on("pageerror", e => errs.push("PAGEERROR: "+String(e).slice(0,300)));
page.on("response", r => { if (r.status()>=400) resp.push(r.status()+" "+r.url()); });
await page.goto("http://127.0.0.1:3001/training", { waitUntil:"networkidle" });
await page.waitForTimeout(3000);
console.log("TITLE:", await page.title());
console.log("--- failed responses ---"); resp.forEach(r=>console.log(r));
console.log("--- console errors ---"); errs.forEach(e=>console.log(e));
console.log("--- visible text ---");
console.log((await page.locator("body").innerText()).slice(0,3000));
await b.close();
